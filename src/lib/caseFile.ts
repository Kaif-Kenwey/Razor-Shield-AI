/* Audit export — resolved cases as CSV                                */
/* ------------------------------------------------------------------ */

function csvCell(value: string | number | null | undefined): string {
  const s = value == null ? "" : String(value);
  // escape quotes, wrap when the cell contains separators/newlines/quotes
  return /[",\n\r]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

export const CASES_CSV_COLUMNS = [
  "case_id",
  "customer_id",
  "customer_name",
  "amount_inr",
  "risk_score",
  "risk_level",
  "signals",
  "ai_recommendation",
  "model_confidence_pct",
  "analyst_action",
  "resolved_by",
  "analyst_note",
  "notebook_entries",
  "opened_at",
  "resolved_at",
] as const;

/**
 * Build an audit-ready CSV of resolved cases (one row per analyst decision).
 * Mirrors the future `GET /investigations/export?format=csv` payload.
 */
export function buildCasesCsv(
  transactions: Transaction[],
  decisions: Record<string, { action: RiskAction; note?: string; at: string; analystId?: string }>,
  caseNotes: Record<string, CaseNote[]> = {},
): string {
  const rows = transactions
    .filter((t) => decisions[t.id])
    .map((t) => {
      const d = decisions[t.id];
      const resolvedBy = d.analystId ? ANALYSTS.find((a) => a.id === d.analystId)?.name ?? "" : "";
      return [
        t.id,
        t.customerId,
        t.customerName,
        t.amount,
        t.riskScore,
        t.riskLevel,
        t.signals.map((s) => s.type).join("|"),
        t.recommendation ?? "",
        t.confidence ?? "",
        d.action,
        resolvedBy,
        d.note ?? "",
        caseNotes[t.id]?.length ?? 0,
        t.timestamp,
        d.at,
      ].map(csvCell).join(",");
    });

  return [
    CASES_CSV_COLUMNS.join(","),
    ...rows,
    "",
    csvCell("RazorShield AI audit export — demo environment, synthetic data only"),
    csvCell(`Exported ${new Date().toISOString()} · ${rows.length} resolved case(s)`),
  ].join("\n");
}

export function downloadCasesCsv(
  transactions: Transaction[],
  decisions: Record<string, { action: RiskAction; note?: string; at: string; analystId?: string }>,
  caseNotes: Record<string, CaseNote[]> = {},
): boolean {
  try {
    const csv = buildCasesCsv(transactions, decisions, caseNotes);
    const stamp = new Date().toISOString().slice(0, 10);
    const blob = new Blob([csv], { type: "text/csv;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `razorshield-audit-${stamp}.csv`;
    document.body.appendChild(a);
    a.click();
    a.remove();
    setTimeout(() => URL.revokeObjectURL(url), 2000);
    return true;
  } catch {
    return false;
  }
}
