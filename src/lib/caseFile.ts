/**
 * RazorShield AI — case file export.
 *
 * Builds a structured, analyst-facing JSON case file (transaction, customer
 * intelligence, AI conclusion, audit trail, analyst decision) and downloads
 * it as a client-side Blob. No backend involved — the same shape maps to a
 * future `GET /investigations/:id/export` endpoint.
 */

import { formatINR } from "@/lib/format";
import { ANALYSTS } from "@/data/mockData";
import type { CaseNote } from "@/store/appStore";
import type { Customer, Investigation, RiskAction, Transaction } from "@/types";

export interface CaseFile {
  document: string;
  version: string;
  exportedAt: string;
  exportedBy: string;
  transaction: Transaction;
  customer: Customer | null;
  ai: {
    summary: string | null;
    recommendation: string | null;
    confidence: number | null;
    evidenceUsed: string[];
    reasoning: string | null;
  };
  decision: {
    action: string;
    note?: string;
    at: string;
    by?: string;
  } | null;
  notebook: CaseNote[];
  provenance: {
    dataSource: string;
    disclaimer: string;
  };
}

export function buildCaseFile(
  txn: Transaction,
  investigation: Investigation | null,
  customer: Customer | null,
  notes: CaseNote[] = [],
  signedInAnalystId = "RK",
): CaseFile {
  const signedIn = ANALYSTS.find((a) => a.id === signedInAnalystId);
  const decision = investigation?.analystAction
    ? {
        action: investigation.analystAction,
        note: investigation.analystNote,
        at: investigation.resolvedAt ?? new Date().toISOString(),
        by: ANALYSTS.find((a) => a.id === signedInAnalystId)?.name,
      }
    : null;

  return {
    document: "RazorShield AI case file",
    version: "1.1",
    exportedAt: new Date().toISOString(),
    exportedBy: signedIn ? `${signedIn.name} · ${signedIn.level} analyst` : "analyst",
    transaction: {
      ...txn,
      investigation: investigation ?? txn.investigation,
    },
    customer,
    ai: {
      summary: txn.aiSummary,
      recommendation: txn.recommendation,
      confidence: txn.confidence,
      evidenceUsed: investigation?.evidenceUsed ?? [],
      reasoning: investigation?.reasoning ?? null,
    },
    decision,
    notebook: notes,
    provenance: {
      dataSource: "Demo environment — synthetic data only",
      disclaimer:
        "Generated by RazorShield AI for the Razorpay AI Buildathon 2026 demo. Scores and evidence are mock values produced by the deterministic demo engine.",
    },
  };
}

/** One-line human-readable header used in toasts / audit notes. */
export function caseFileHeadline(caseFile: CaseFile): string {
  const t = caseFile.transaction;
  return `${t.id} · ${formatINR(t.amount)} · ${t.riskScore}/100 · ${caseFile.decision?.action ?? "open"}`;
}

export function downloadCaseFile(caseFile: CaseFile): boolean {
  try {
    const blob = new Blob([JSON.stringify(caseFile, null, 2)], {
      type: "application/json",
    });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `${caseFile.transaction.id}-case-file.json`;
    document.body.appendChild(a);
    a.click();
    a.remove();
    setTimeout(() => URL.revokeObjectURL(url), 2000);
    return true;
  } catch {
    return false;
  }
}

